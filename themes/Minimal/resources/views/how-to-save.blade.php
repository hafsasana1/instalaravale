            <h1>How to Download Instagram Audio</h1>
            <p>Follow these simple steps to save audio from any public Instagram Reel, Post, Story or Video as an MP3 or M4A file.</p>

            <h2>Step 1 — Find the Instagram content</h2>
            <p>Open the Instagram app on your phone or visit instagram.com on your computer. Navigate to the Reel, Post, Story, or Video whose audio you want to save.</p>

            <h2>Step 2 — Copy the link</h2>
            <p>On mobile: Tap the three-dot menu <strong>···</strong> in the top-right corner of the post, then tap <strong>"Copy Link"</strong>.</p>
            <p>On desktop: Click the three-dot menu, then select <strong>"Copy Link"</strong> or copy the URL directly from your browser's address bar.</p>

            <h2>Step 3 — Paste on ReelSound</h2>
            <p>Come back to this page and paste the copied link into the input field at the top. Click the <strong>"Paste"</strong> button or use Ctrl+V / Cmd+V.</p>

            <h2>Step 4 — Choose your audio format</h2>
            <p>Select <strong>MP3</strong> for universal compatibility (works on all devices and players) or <strong>M4A</strong> for higher audio quality at a smaller file size.</p>

            <h2>Step 5 — Download</h2>
            <p>Click <strong>"Download Audio"</strong>. The audio will be extracted in real-time and your browser will prompt you to save the file. This may take 15–30 seconds depending on the video length.</p>

            <h2>Tips</h2>
            <ul>
                <li>Only public Instagram accounts work — private accounts are inaccessible.</li>
                <li>The link must be from instagram.com (not a third-party app share link).</li>
                <li>If a download fails, try opening the Instagram post directly in your browser and copying that URL.</li>
                <li>Downloaded files are saved to your browser's default download folder.</li>
            </ul>
